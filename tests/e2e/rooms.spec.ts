import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';

test('import, draw, move, link, validate, undo, save and reopen rooms', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.goto('/');
  await page.getByRole('button', { name: 'Add room', exact: true }).click();
  await page.getByLabel('Room name', { exact: true }).fill('Foyer');
  await page.getByLabel('Import background', { exact: true }).setInputFiles('fixtures/backgrounds/foyer.png');
  await expect(page.getByRole('img', { name: 'Foyer background' })).toBeVisible();
  await page.getByRole('button', { name: 'Draw hotspot', exact: true }).click();
  const canvas = await page.locator('#room-stage').boundingBox();
  if (!canvas) throw new Error('Missing canvas');
  await page.mouse.move(canvas.x + canvas.width * .3, canvas.y + canvas.height * .7);
  await page.mouse.down();
  await page.mouse.move(canvas.x + canvas.width * .1, canvas.y + canvas.height * .2, { steps: 8 });
  await page.mouse.up();
  await page.getByLabel('Hotspot name', { exact: true }).fill('Study door');
  const drawnX = Number(await page.getByLabel('X (%)', { exact: true }).inputValue());
  expect(Math.abs(drawnX - 10)).toBeLessThan(.2);
  expect(Math.abs(Number(await page.getByLabel('Width (%)', { exact: true }).inputValue()) - 20)).toBeLessThan(.2);
  await page.getByRole('button', { name: 'Select hotspot Study door', exact: true }).press('ArrowRight');
  await expect(page.getByLabel('X (%)', { exact: true })).toHaveValue((drawnX + 1).toFixed(2));
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByLabel('X (%)', { exact: true })).toHaveValue(drawnX.toFixed(2));
  const hit = await page.getByRole('button', { name: 'Select hotspot Study door', exact: true }).boundingBox();
  if (!hit) throw new Error('Missing hotspot');
  await page.mouse.move(hit.x + hit.width / 2, hit.y + hit.height / 2);
  await page.mouse.down();
  await page.mouse.move(hit.x + hit.width / 2 + canvas.width * .05, hit.y + hit.height / 2, { steps: 6 });
  await page.mouse.up();
  expect(Math.abs(Number(await page.getByLabel('X (%)', { exact: true }).inputValue()) - drawnX - 5)).toBeLessThan(.2);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByLabel('X (%)', { exact: true })).toHaveValue(drawnX.toFixed(2));
  await page.getByRole('button', { name: 'Draw hotspot', exact: true }).click();
  await page.mouse.move(canvas.x + canvas.width * .5, canvas.y + canvas.height * .5);
  await page.mouse.down();
  await page.mouse.move(canvas.x + canvas.width * .8, canvas.y + canvas.height * .8);
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await expect(page.locator('#room-stage .hotspot')).toHaveCount(1);
  await page.getByRole('button', { name: 'Add room', exact: true }).click();
  await page.getByLabel('Room name', { exact: true }).fill('Study');
  await page.getByLabel('Import background', { exact: true }).setInputFiles('fixtures/backgrounds/study.png');
  await expect(page.getByRole('img', { name: 'Study background' })).toBeVisible();
  await page.getByRole('button', { name: 'Foyer', exact: true }).click();
  await page.getByRole('button', { name: 'Select hotspot Study door', exact: true }).click();
  await page.getByRole('combobox', { name: 'Action', exact: true }).selectOption('go_to');
  await page.getByRole('combobox', { name: 'Destination room', exact: true }).selectOption({ label: 'Study' });
  await expect(page.getByText('Validation · 0', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Study', exact: true }).click();
  await page.getByRole('button', { name: 'Delete room', exact: true }).click();
  await page.locator('.issue').filter({ hasText: 'action.room_id' }).click();
  await expect(page.getByLabel('Hotspot name', { exact: true })).toHaveValue('Study door');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByText('Validation · 0', { exact: true })).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const download = await downloadPromise;
  const file = testInfo.outputPath('rooms.pace-draft.json');
  await download.saveAs(file);
  const saved = JSON.parse(await fs.readFile(file, 'utf8'));
  expect(saved.rooms).toHaveLength(2);
  expect(saved.rooms[0].hotspots[0].action.room_id).toBe(saved.rooms[1].id);
  expect(saved.rooms[0].background.data_url).toMatch(/^data:image\/png;base64,/);
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Open project', { exact: true }).setInputFiles(file);
  await expect(page.getByRole('heading', { name: 'Foyer', exact: true })).toBeVisible();
  const secondPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const second = await secondPromise;
  await second.saveAs(testInfo.outputPath('roundtrip.json'));
  expect(JSON.parse(await fs.readFile(testInfo.outputPath('roundtrip.json'), 'utf8'))).toEqual(saved);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Foyer', exact: true })).toBeVisible();
  const malformed = testInfo.outputPath('unsupported.json');
  await fs.writeFile(malformed, JSON.stringify({ ...saved, version: 999 }));
  await page.getByLabel('Open project', { exact: true }).setInputFiles(malformed);
  await expect(page.getByRole('status')).toContainText('Unsupported draft version');
  await expect(page.getByRole('heading', { name: 'Foyer', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
